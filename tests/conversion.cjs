const { readFileSync } = require('node:fs');
const vm = require('node:vm');
const ts = require('typescript');
const assert = require('node:assert/strict');
const context = vm.createContext({});
vm.runInContext(ts.transpile(readFileSync('tokens.ts', 'utf8'), { target: ts.ScriptTarget.ES2022 }), context);
const convert = context.convertTokens;
const collection = { id: 'c', name: 'Theme', modes: [{ modeId: 'light', name: 'Light' }, { modeId: 'dark', name: 'Dark' }], defaultModeId: 'light' };
const variable = (id, name, type, light, dark = light) => ({ id, name, resolvedType: type, description: '', variableCollectionId: 'c', valuesByMode: { light, dark } });
const vars = [variable('a', 'base', 'FLOAT', 1, 2), variable('b', 'alias', 'FLOAT', { type: 'VARIABLE_ALIAS', id: 'a' }), variable('s', 'name', 'STRING', 'hello'), variable('t', 'enabled', 'BOOLEAN', true), variable('color', 'color', 'COLOR', { r: 1, g: 0, b: 0, a: .5 })];
const result = convert([collection], vars, [], 'Test');
assert.equal(result.document.version, '2025.10');
assert.equal(result.document.modifiers.c.default, 'Light');
assert.equal(result.document.modifiers.c.contexts.Dark[0].variables.Theme.base.$value, 2);
assert.equal(result.document.modifiers.c.contexts.Light[0].variables.Theme.alias.$value, '{variables.Theme.base}');
assert.equal(result.document.modifiers.c.contexts.Light[0].variables.Theme.color.$value.alpha, .5);
assert.throws(() => convert([collection], [variable('b', 'broken', 'FLOAT', { type: 'VARIABLE_ALIAS', id: 'missing' })], [], ''), /alias/);
assert.throws(() => convert([collection], [variable('a', 'cycle', 'FLOAT', { type: 'VARIABLE_ALIAS', id: 'a' })], [], ''), /Circular/);
assert.throws(() => convert([collection], [variable('a', 'x', 'FLOAT', 1), variable('b', 'x/y', 'FLOAT', 2)], [], ''), /collision/);
const styles = [{ id: 'p', name: 'Red', description: '', kind: 'paint', data: { paints: [{ type: 'SOLID', color: { r: 1, g: 0, b: 0 } }] } }, { id: 'g', name: 'Grid', description: '', kind: 'grid', data: { layoutGrids: [] } }];
const styled = convert([], [], styles, 'Styles');
assert.equal(styled.document.sets.styles.sources[0].styles.paint.Red.$type, 'color');
assert.equal(styled.warnings.length, 1);
assert.ok(styled.document.sets.styles.sources[0].styles.grid.Grid.$extensions['io.crossfigma']);
console.log('Conversion fixtures passed');
